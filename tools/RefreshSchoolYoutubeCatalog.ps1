param(
    [string]$ApiKey = (Get-Clipboard -Raw).Trim()
)

$ErrorActionPreference = 'Stop'
if ($ApiKey -notmatch '^AIza[\w-]{35}$') { throw 'YouTube Data API key tidak tersedia.' }

$projectRoot = Split-Path -Parent $PSScriptRoot
$source = Get-Content (Join-Path $projectRoot 'app\src\main\java\com\mugarutv\data\repository\SchoolBackend.kt') -Raw
$playlists = [regex]::Matches($source, '"([^"\r\n]+)"\s+to\s+"(PL[\w-]+)"') | ForEach-Object {
    [pscustomobject]@{ Name = $_.Groups[1].Value; Id = $_.Groups[2].Value }
}
$channelId = 'UCRUYr8IDtd_OSbEOgE-z1Iw'

function Get-PlaylistItems([string]$playlistId) {
    $items = [System.Collections.Generic.List[object]]::new()
    $pageToken = ''
    do {
        $uri = 'https://www.googleapis.com/youtube/v3/playlistItems?part=snippet,contentDetails&maxResults=50&playlistId=' +
            [uri]::EscapeDataString($playlistId) + '&pageToken=' + [uri]::EscapeDataString($pageToken) +
            '&key=' + [uri]::EscapeDataString($ApiKey)
        try { $result = Invoke-RestMethod -Uri $uri -TimeoutSec 30 }
        catch { throw "Gagal membaca playlist $playlistId dari YouTube Data API." }
        foreach ($item in $result.items) { $items.Add($item) }
        $pageToken = [string]$result.nextPageToken
    } while ($pageToken)
    return $items.ToArray()
}

$uploadsId = 'UU' + $channelId.Substring(2)
$uploads = @(Get-PlaylistItems $uploadsId)
$videos = @{}
foreach ($item in $uploads) {
    $id = [string]$item.contentDetails.videoId
    if ($id -notmatch '^[A-Za-z0-9_-]{11}$' -or $item.snippet.title -in @('Private video', 'Deleted video')) { continue }
    $videos[$id] = [ordered]@{
        id = $id
        title = [string]$item.snippet.title
        publishedAt = ([datetime]$item.contentDetails.videoPublishedAt).ToUniversalTime().ToString('yyyy-MM-ddTHH:mm:ssZ')
        categories = [System.Collections.Generic.List[string]]::new()
    }
}

foreach ($playlist in $playlists) {
    $members = @(Get-PlaylistItems $playlist.Id)
    foreach ($item in $members) {
        $id = [string]$item.contentDetails.videoId
        if ($videos.ContainsKey($id) -and -not $videos[$id].categories.Contains($playlist.Name)) {
            $videos[$id].categories.Add($playlist.Name)
        }
    }
    Write-Output "$($playlist.Name): $($members.Count) anggota"
}

$catalog = foreach ($video in $videos.Values) {
    [ordered]@{
        id = $video.id
        title = $video.title
        publishedAt = $video.publishedAt
        categories = @($video.categories.ToArray())
    }
}
$catalog = @($catalog | Sort-Object { [datetime]$_['publishedAt'] } -Descending)
$document = [ordered]@{
    channelId = $channelId
    generatedAt = (Get-Date).ToUniversalTime().ToString('yyyy-MM-ddTHH:mm:ssZ')
    count = $catalog.Count
    items = $catalog
}
$outputPath = Join-Path $projectRoot 'backend\school_youtube_catalog.json'
$document | ConvertTo-Json -Depth 7 | Set-Content -LiteralPath $outputPath -Encoding utf8
Write-Output "Katalog channel: $($catalog.Count) video; tersimpan di backend\school_youtube_catalog.json"

function Kotlin-String([string]$value) {
    return '"' + $value.Replace('\', '\\').Replace('"', '\"').Replace('$', '\$').Replace("`r", '\r').Replace("`n", '\n').Replace("`t", '\t') + '"'
}

$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add('package com.mugarutv.data.repository')
$lines.Add('')
$lines.Add('// Generated by tools/RefreshSchoolYoutubeCatalog.ps1 from YouTube Data API v3.')
$lines.Add('internal data class SchoolCatalogItem(val id: String, val title: String, val publishedAt: String, val categories: List<String>)')
$lines.Add('internal val SCHOOL_YOUTUBE_CATALOG = listOf(')
foreach ($video in $catalog) {
    $categoryValues = @($video.categories | ForEach-Object { Kotlin-String $_ })
    $categoryCode = if ($categoryValues.Count) { 'listOf(' + ($categoryValues -join ', ') + ')' } else { 'emptyList()' }
    $lines.Add('    SchoolCatalogItem(' + (Kotlin-String $video.id) + ', ' + (Kotlin-String $video.title) + ', ' +
        (Kotlin-String $video.publishedAt) + ', ' + $categoryCode + '),')
}
$lines.Add(')')
$kotlinPath = Join-Path $projectRoot 'app\src\main\java\com\mugarutv\data\repository\SchoolYoutubeCatalog.kt'
$lines | Set-Content -LiteralPath $kotlinPath -Encoding utf8
Write-Output 'Kode Kotlin katalog diperbarui.'
